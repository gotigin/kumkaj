#!/usr/bin/env bash
# Build the khaynjo.com world shelf (chapter 8 pager + chapter 1 strip) from
# the world-food research pack — one famous dish per country, English +
# native names, public-domain / CC0 photos where the pack has one.
#
#   ./sites/khaynjo/scripts/build-world-shelf.sh [research_dir]
#
# research_dir defaults to local/khaynjo/world-food-research (gitignored
# staging; the site never reads local/ at runtime). Writes:
#   sites/khaynjo/resources/dishes/world/<country-slug>.webp   600×400, q80
#   sites/khaynjo/resources/dishes/world/SOURCES.md            photo sources
#   sites/khaynjo/src/world_shelf.rs                           generated table
# Countries without a photo keep their names and show an honest "photo
# coming" card (research SKIPS.md). Re-run after the pack changes.
# bash + jq + ImageMagick (no Python).
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../../.." && pwd)"
SITE="$ROOT/sites/khaynjo"
PACK="${1:-$ROOT/local/khaynjo/world-food-research}"
OUT_IMG="$SITE/resources/dishes/world"
OUT_RS="$SITE/src/world_shelf.rs"
W=600
H=400
Q=80

# Reviewed 2026-11-12: research photos that do not show the plated dish
# (people, shop fronts, signs, landscapes, packaging, clip-art, wrong cuisine).
# These countries keep their names and show the "photo coming" card.
# Cleared after re-check: Ethiopia (Injera and doro wat), Hungary (Gulyásleves),
# Suriname (Pom gerecht), Fiji (Ota ika ≈ kokoda).
declare -A REJECT=(
  [Dominica]="no plated mountain chicken under free license"
  [Marshall_Islands]="Filipino ginataan, not Māāj"
  [Micronesia]="people carrying food, not Kon"
  [Palau]="dried leaves, not demok"
  [Niue]="medical diagram (kidney), not takihi"
  [Oman]="no plated shuwa under free license"
  [Tuvalu]="pulaka plant field, not the dish"
)
# Sources narrower than this are upscaled thumbnails — too soft for a card.
MIN_SRC_W=280

for tool in jq magick; do
  command -v "$tool" >/dev/null 2>&1 || { echo "error: $tool required" >&2; exit 1; }
done
[[ -f "$PACK/index.json" ]] || { echo "error: no $PACK/index.json" >&2; exit 1; }

slugify() {
  printf '%s' "$1" | iconv -f UTF-8 -t ASCII//TRANSLIT 2>/dev/null \
    | tr '[:upper:]' '[:lower:]' | sed -E 's/[^a-z0-9]+/-/g; s/^-+//; s/-+$//'
}

mkdir -p "$OUT_IMG"
TMP_RS="$(mktemp)"
TMP_SRC="$(mktemp)"
TMP_REJ="$(mktemp)"
TMP_MISS="$(mktemp)"
trap 'rm -f "$TMP_RS" "$TMP_SRC" "$TMP_REJ" "$TMP_MISS"' EXIT
declare -A KEEP=()
n=0
photos=0

{
  echo "//! GENERATED by sites/khaynjo/scripts/build-world-shelf.sh from the"
  echo "//! world-food research pack — do not edit by hand; re-run the script."
  echo "//! One famous dish per country: English + native names, photo file under"
  echo "//! resources/dishes/world/ when the pack has a public-domain / CC0 one."
  echo
  echo "pub struct WorldDish {"
  echo "    pub country: &'static str,"
  echo "    pub country_native: &'static str,"
  echo "    pub dish: &'static str,"
  echo "    pub dish_native: &'static str,"
  echo "    /// File name under resources/dishes/world/ (None = photo coming)."
  echo "    pub photo: Option<&'static str>,"
  echo "}"
  echo
  echo "pub const WORLD: &[WorldDish] = &["
} > "$TMP_RS"

printf '# World shelf photo sources\n\nGenerated by `sites/khaynjo/scripts/build-world-shelf.sh`. Photos are free\nlicenses (public domain / CC0 / CC BY / CC BY-SA) or an existing Khaynjo\nsite still, resized to %sx%s WebP. Attribution for BY/SA lives in the Source\ncolumn.\n\n| Country | Dish | File | Source |\n|---|---|---|---|\n' "$W" "$H" > "$TMP_SRC"

while IFS= read -r folder; do
  meta="$PACK/$folder/metadata.json"
  [[ -f "$meta" ]] || { echo "warn: $folder has no metadata.json" >&2; continue; }
  country="$(jq -r '.country_en' "$meta")"
  slug="$(slugify "$country")"
  image="$(jq -r '.image // ""' "$meta")"
  photo="None"
  why=""
  if [[ -n "$image" && -f "$PACK/$folder/$image" ]]; then
    src_w="$(magick identify -quiet -format "%w" "$PACK/$folder/$image[0]" 2>/dev/null || echo 0)"
    if [[ -n "${REJECT[$folder]:-}" ]]; then
      why="${REJECT[$folder]}"
    elif (( src_w < MIN_SRC_W )); then
      why="source only ${src_w}px wide"
    fi
  fi
  if [[ -n "$why" ]]; then
    printf "| %s | %s | — | not shown: %s |\n" "$country" "$(jq -r .dish_en "$meta")" "$why" >> "$TMP_REJ"
    printf "| %s | %s | — | %s |\n" "$country" "$(jq -r .dish_en "$meta")" "$why" >> "$TMP_MISS"
  elif [[ -n "$image" && -f "$PACK/$folder/$image" ]]; then
    file="$slug.webp"
    dest="$OUT_IMG/$file"
    src="$PACK/$folder/$image"
    # Re-encode only when the source changed (keeps git diffs quiet).
    if [[ ! -f "$dest" || "$src" -nt "$dest" ]]; then
      magick -quiet "$src" -auto-orient -resize "${W}x${H}^" -gravity center \
        -extent "${W}x${H}" -strip -quality "$Q" -define webp:method=6 "webp:$dest"
    fi
    KEEP["$file"]=1
    photo="Some(\"$file\")"
    photos=$((photos + 1))
    jq -r --arg file "$file" \
      '"| \(.country_en) | \(.dish_en) | \($file) | \((.image_source // "") | gsub("\\|"; "/")) |"' \
      "$meta" >> "$TMP_SRC"
  else
    printf "| %s | %s | — | no free plated photo in research pack yet |\n" \
      "$country" "$(jq -r .dish_en "$meta")" >> "$TMP_MISS"
  fi
  # @json strings are valid Rust literals here (non-ASCII stays raw); refuse
  # \u escapes, which Rust spells differently.
  line="$(jq -r --arg photo "$photo" '
    "    WorldDish { country: \(.country_en | @json), country_native: \(.country_native // .country_en | @json), dish: \(.dish_en | @json), dish_native: \(.dish_native // .dish_en | @json), photo: \($photo) },"
  ' "$meta")"
  if [[ "$line" == *'\u'* ]]; then
    echo "error: $folder has a control character in its names" >&2
    exit 1
  fi
  printf '%s\n' "$line" >> "$TMP_RS"
  n=$((n + 1))
done < <(jq -r '.countries[].folder' "$PACK/index.json")

echo "];" >> "$TMP_RS"

# Photos no longer in the pack.
for f in "$OUT_IMG"/*.webp; do
  [[ -e "$f" ]] || continue
  b="$(basename "$f")"
  [[ -n "${KEEP[$b]:-}" ]] || { rm -f "$f"; echo "  removed stale $b"; }
done

mv "$TMP_RS" "$OUT_RS"
if [[ -s "$TMP_REJ" ]]; then
  printf '\n## Research photos not shown\n\n| Country | Dish | File | Reason |\n|---|---|---|---|\n' >> "$TMP_SRC"
  cat "$TMP_REJ" >> "$TMP_SRC"
fi
if [[ -s "$TMP_MISS" ]]; then
  miss_n="$(wc -l < "$TMP_MISS" | tr -d ' ')"
  printf '\n## Photo coming (%s countries)\n\nCards keep names and show “Photo coming” until a free-license plated\ndish is in the research pack. Open work: `sites/khaynjo/README.md` § Remaining.\n\n| Country | Dish | File | Reason |\n|---|---|---|---|\n' "$miss_n" >> "$TMP_SRC"
  cat "$TMP_MISS" >> "$TMP_SRC"
fi
mv "$TMP_SRC" "$OUT_IMG/SOURCES.md"
rm -f "$TMP_REJ" "$TMP_MISS"
trap - EXIT
echo "world shelf: $n countries, $photos photos → $OUT_IMG ($(du -sh "$OUT_IMG" | cut -f1)), $OUT_RS"

# Every Han / kana / Hangul character on the shelf must be in the 12 KB CJK
# subset WorldFont carries (resources/fonts/NotoSansCJK-WorldShelf.otf), or
# those cards draw empty boxes. Regenerate the subset when this fails:
#   hb-subset /usr/share/fonts/noto-cjk/NotoSansCJK-Regular.ttc --face-index=2 \
#     --text-file=<chars> -o sites/khaynjo/resources/fonts/NotoSansCJK-WorldShelf.otf
CJK_FONT="$SITE/resources/fonts/NotoSansCJK-WorldShelf.otf"
if command -v fc-query >/dev/null 2>&1 && [[ -f "$CJK_FONT" ]]; then
  need="$(LC_ALL=C.UTF-8 grep -oP '[\p{Han}\p{Hangul}\p{Hiragana}\p{Katakana}]' "$OUT_RS" | LC_ALL=C sort -u \
    | while IFS= read -r ch; do printf '%x\n' "'$ch"; done)"
  have="$(fc-query --format='%{charset}' "$CJK_FONT")"
  missing="$(printf '%s\n' "$need" | awk -v have="$have" '
    BEGIN { n = split(have, r, " "); for (i = 1; i <= n; i++) {
      split(r[i], ab, "-"); lo[i] = strtonum("0x" ab[1]); hi[i] = strtonum("0x" (ab[2] == "" ? ab[1] : ab[2])) } }
    NF { cp = strtonum("0x" $1); ok = 0
      for (i = 1; i <= n; i++) if (cp >= lo[i] && cp <= hi[i]) { ok = 1; break }
      if (!ok) printf "U+%04X ", cp }')"
  if [[ -n "$missing" ]]; then
    echo "error: CJK subset lacks $missing— regenerate $CJK_FONT (see comment above)" >&2
    exit 1
  fi
  echo "  CJK subset covers all $(printf '%s\n' "$need" | grep -c .) shelf characters"
fi

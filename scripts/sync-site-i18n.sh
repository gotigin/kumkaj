#!/usr/bin/env bash
# Sync the shared website language pieces into every Kumkaj site.
#
#   ./scripts/sync-site-i18n.sh
#
# - sites/_shared/i18n/languages.rs ← the LANGUAGES table of apps/khaynjo/src/locale.rs
#   (the sites' 115-language catalogue = the apps'; check-language-parity.sh compares)
# - sites/<site>/static/js/{lang-nav,site-i18n}.js ← sites/_shared/chrome/
# Run after changing the catalogue or either script. Bash + awk only.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SITES=(khaynjo moklanjo kirano tabiyat kumkaj)
OUT="$ROOT/sites/_shared/i18n/languages.rs"

{
  echo '// GENERATED by scripts/sync-site-i18n.sh from apps/khaynjo/src/locale.rs — do not edit.'
  echo '// Same 115-language catalogue as the apps (docs/WEBSITES.md hard rule;'
  echo '// scripts/check-language-parity.sh compares it).'
  awk '/^pub const LANGUAGES: &\[LanguageInfo\] = &\[/,/^\];/' "$ROOT/apps/khaynjo/src/locale.rs"
} > "$OUT.tmp"
n="$(grep -c 'LanguageInfo {' "$OUT.tmp" || true)"
if [[ "$n" -lt 100 ]]; then
  rm -f "$OUT.tmp"
  echo "error: read only $n languages from apps/khaynjo/src/locale.rs" >&2
  exit 1
fi
mv "$OUT.tmp" "$OUT"

for site in "${SITES[@]}"; do
  js="$ROOT/sites/$site/static/js"
  mkdir -p "$js"
  cp -f "$ROOT/sites/_shared/chrome/lang-nav.js" "$js/lang-nav.js"
  cp -f "$ROOT/sites/_shared/chrome/site-i18n.js" "$js/site-i18n.js"
done
echo "languages.rs: $n languages; lang-nav.js + site-i18n.js → ${SITES[*]}"

#!/usr/bin/env bash
# Moklanjo's desktop install / data path helpers (shipped inside its
# packages; apps/khaynjo/scripts has Khaynjo's own copy).
# Requires KUMKAJ_APP_ID and KUMKAJ_APP_LABEL (from env/*.env or
# install-manifest.env). Overrides: KUMKAJ_INSTALL_SLUG, KUMKAJ_BIN_NAME,
# KUMKAJ_PROGRAMS_NAME. Defaults are Moklanjo's.
#
# Moklanjo prod:  com.moklanjo       · "Moklanjo"
# Moklanjo dev:   com.moklanjo.debug · "Moklanjo Dev"

desktop_is_debug() {
  [[ "${KUMKAJ_APP_ID:-}" == *.debug ]] || [[ "${KUMKAJ_ENV:-}" == "development" ]]
}

# Short folder slug under ~/.local/lib and for package layout (no spaces).
desktop_install_slug() {
  local base="${KUMKAJ_INSTALL_SLUG:-kumkaj-moklanjo}"
  if desktop_is_debug; then
    echo "$base-debug"
  else
    echo "$base"
  fi
}

# Windows Programs folder name (spaces OK). The env label already
# carries the Dev suffix on development builds.
desktop_programs_name() {
  echo "${KUMKAJ_PROGRAMS_NAME:-${KUMKAJ_APP_LABEL:-Moklanjo}}"
}

# CLI / shortcut binary base name.
desktop_bin_name() {
  local base="${KUMKAJ_BIN_NAME:-kumkaj-moklanjo}"
  if desktop_is_debug; then
    echo "$base-dev"
  else
    echo "$base"
  fi
}

# Freedesktop desktop file id (no .desktop suffix).
desktop_entry_id() {
  echo "${KUMKAJ_APP_ID:-com.moklanjo}"
}

# Books / SQLite data directory (same key the app uses via dirs::data_dir + APP_ID).
desktop_data_dir_linux() {
  echo "${XDG_DATA_HOME:-$HOME/.local/share}/${KUMKAJ_APP_ID:?}"
}

desktop_data_dir_windows_hint() {
  echo "%APPDATA%\\${KUMKAJ_APP_ID:?}"
}

# Installed app files: binary + resources + uninstall + manifest.
desktop_install_dir_linux() {
  if [[ -n "${DESKTOP_INSTALL_DIR_LINUX:-}" ]]; then
    echo "$DESKTOP_INSTALL_DIR_LINUX"
    return
  fi
  echo "$HOME/.local/lib/$(desktop_install_slug)"
}

desktop_bin_dir_linux() {
  echo "${XDG_BIN_HOME:-$HOME/.local/bin}"
}

desktop_applications_dir_linux() {
  echo "${XDG_DATA_HOME:-$HOME/.local/share}/applications"
}

# Write a small manifest the uninstaller reads (re-runnable after partial delete).
desktop_write_manifest() {
  local dest="${1:?}"
  mkdir -p "$(dirname "$dest")"
  cat >"$dest" <<EOF
# Generated by Kumkaj desktop install — do not edit unless you know why.
KUMKAJ_ENV=${KUMKAJ_ENV:-production}
KUMKAJ_APP_ID=${KUMKAJ_APP_ID:?}
KUMKAJ_APP_LABEL=${KUMKAJ_APP_LABEL:?}
INSTALL_SLUG=$(desktop_install_slug)
BIN_NAME=$(desktop_bin_name)
ENTRY_ID=$(desktop_entry_id)
INSTALLED_AT=$(date -u +%Y-%m-%dT%H:%M:%SZ)
EOF
}

desktop_load_manifest() {
  local file="${1:?}"
  [[ -f "$file" ]] || return 1
  while IFS= read -r line || [[ -n "$line" ]]; do
    line="${line#"${line%%[![:space:]]*}"}"
    [[ -z "$line" || "$line" == \#* ]] && continue
    [[ "$line" != *=* ]] && continue
    local key="${line%%=*}"
    local value="${line#*=}"
    export "$key=$value"
  done <"$file"
}

# Prompt for which local data categories to wipe. Sets DESKTOP_WIPE_ARGS to a
# space-separated list of --uninstall-wipe categories (trading / schema / ui),
# or empty if the owner keeps everything. Returns 0 when any wipe was chosen.
desktop_prompt_wipe_data() {
  local data_dir="${1:?}"
  local label="${KUMKAJ_APP_LABEL:-Moklanjo}"
  DESKTOP_WIPE_ARGS=""
  echo
  echo "$label — local data:"
  echo "  $data_dir"
  if [[ ! -e "$data_dir" ]]; then
    echo "  (no data directory found — nothing to remove)"
    return 1
  fi
  if [[ ! -t 0 ]]; then
    echo "(non-interactive: keeping all local data)"
    return 1
  fi
  local ans_records="" ans_setup="" ans_ui=""
  echo
  echo "Delete business records (sales, payments, day books)? Shop setup stays. [y/N]"
  read -r -p "> " ans_records || true
  echo "Delete shop setup (products, rates, staff, brand, empty books)? [y/N]"
  read -r -p "> " ans_setup || true
  echo "Delete screen preferences (sidebar, amounts, window, language)? [y/N]"
  read -r -p "> " ans_ui || true
  local cats=()
  case "${ans_setup,,}" in
    y|yes) cats+=(schema) ;;
    *)
      case "${ans_records,,}" in
        y|yes) cats+=(trading) ;;
      esac
      ;;
  esac
  case "${ans_ui,,}" in
    y|yes) cats+=(ui) ;;
  esac
  if [[ ${#cats[@]} -eq 0 ]]; then
    return 1
  fi
  DESKTOP_WIPE_ARGS="${cats[*]}"
  return 0
}

# Run `$1 --uninstall-wipe $DESKTOP_WIPE_ARGS`, or fall back to folder deletes.
desktop_apply_wipe_data() {
  local data_dir="${1:?}"
  local exe="${2:-}"
  if [[ -z "${DESKTOP_WIPE_ARGS:-}" ]]; then
    return 0
  fi
  if [[ -n "$exe" && -x "$exe" ]]; then
    echo "Wiping: $DESKTOP_WIPE_ARGS"
    "$exe" --uninstall-wipe $DESKTOP_WIPE_ARGS || true
    return 0
  fi
  echo "App exe not available; applying folder deletes for: $DESKTOP_WIPE_ARGS"
  local a
  for a in $DESKTOP_WIPE_ARGS; do
    case "$a" in
      schema)
        rm -rf "$data_dir/servers" "$data_dir/client" "$data_dir/backups"
        rm -f "$data_dir/servers.json"
        ;;
      ui)
        rm -f "$data_dir/window_geom.json" "$data_dir/app_language.json"
        ;;
      trading)
        echo "  (business records need the app binary; choose shop setup to remove databases)"
        ;;
    esac
  done
  rmdir "$data_dir" 2>/dev/null || true
}

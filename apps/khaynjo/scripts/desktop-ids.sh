#!/usr/bin/env bash
# Khaynjo's desktop install / data path helpers (shipped inside its
# packages; apps/courier/scripts has Courier's own copy).
# Requires KUMKAJ_APP_ID and KUMKAJ_APP_LABEL (from env/*.env or
# install-manifest.env). Overrides: KUMKAJ_INSTALL_SLUG, KUMKAJ_BIN_NAME,
# KUMKAJ_PROGRAMS_NAME. Defaults are Khaynjo's.
#
# Khaynjo prod:  com.khaynjo       · "Khaynjo"
# Khaynjo dev:   com.khaynjo.debug · "Khaynjo Dev"

desktop_is_debug() {
  [[ "${KUMKAJ_APP_ID:-}" == *.debug ]] || [[ "${KUMKAJ_ENV:-}" == "development" ]]
}

# Short folder slug under ~/.local/lib and for package layout (no spaces).
desktop_install_slug() {
  local base="${KUMKAJ_INSTALL_SLUG:-kumkaj-khaynjo}"
  if desktop_is_debug; then
    echo "$base-debug"
  else
    echo "$base"
  fi
}

# Windows Programs folder name (spaces OK). The env label already
# carries the Dev suffix on development builds.
desktop_programs_name() {
  echo "${KUMKAJ_PROGRAMS_NAME:-${KUMKAJ_APP_LABEL:-Khaynjo}}"
}

# CLI / shortcut binary base name.
desktop_bin_name() {
  local base="${KUMKAJ_BIN_NAME:-kumkaj-khaynjo}"
  if desktop_is_debug; then
    echo "$base-dev"
  else
    echo "$base"
  fi
}

# Freedesktop desktop file id (no .desktop suffix).
desktop_entry_id() {
  echo "${KUMKAJ_APP_ID:-com.khaynjo}"
}

# Books / SQLite data directory (same key the app uses via dirs::data_dir + APP_ID).
desktop_data_dir_linux() {
  echo "${XDG_DATA_HOME:-$HOME/.local/share}/${KUMKAJ_APP_ID:?}"
}

desktop_data_dir_windows_hint() {
  echo "%APPDATA%\\${KUMKAJ_APP_ID:?}"
}

# Installed app files: binary + resources + uninstall + manifest.
desktop_install_dir_linux() {
  if [[ -n "${DESKTOP_INSTALL_DIR_LINUX:-}" ]]; then
    echo "$DESKTOP_INSTALL_DIR_LINUX"
    return
  fi
  echo "$HOME/.local/lib/$(desktop_install_slug)"
}

desktop_bin_dir_linux() {
  echo "${XDG_BIN_HOME:-$HOME/.local/bin}"
}

desktop_applications_dir_linux() {
  echo "${XDG_DATA_HOME:-$HOME/.local/share}/applications"
}

# Write a small manifest the uninstaller reads (re-runnable after partial delete).
desktop_write_manifest() {
  local dest="${1:?}"
  mkdir -p "$(dirname "$dest")"
  cat >"$dest" <<EOF
# Generated by Kumkaj desktop install — do not edit unless you know why.
KUMKAJ_ENV=${KUMKAJ_ENV:-production}
KUMKAJ_APP_ID=${KUMKAJ_APP_ID:?}
KUMKAJ_APP_LABEL=${KUMKAJ_APP_LABEL:?}
INSTALL_SLUG=$(desktop_install_slug)
BIN_NAME=$(desktop_bin_name)
ENTRY_ID=$(desktop_entry_id)
INSTALLED_AT=$(date -u +%Y-%m-%dT%H:%M:%SZ)
EOF
}

desktop_load_manifest() {
  local file="${1:?}"
  [[ -f "$file" ]] || return 1
  while IFS= read -r line || [[ -n "$line" ]]; do
    line="${line#"${line%%[![:space:]]*}"}"
    [[ -z "$line" || "$line" == \#* ]] && continue
    [[ "$line" != *=* ]] && continue
    local key="${line%%=*}"
    local value="${line#*=}"
    export "$key=$value"
  done <"$file"
}

# Prompt: keep data (default) or remove. Returns 0 if caller should delete data.
desktop_prompt_remove_data() {
  local data_dir="${1:?}"
  local label="${KUMKAJ_APP_LABEL:-Khaynjo}"
  echo
  echo "$label — local books data:"
  echo "  $data_dir"
  if [[ ! -e "$data_dir" ]]; then
    echo "  (no data directory found — nothing to remove)"
    return 1
  fi
  echo
  echo "Remove this data? (books, backups, settings)"
  echo "  y = delete data forever"
  echo "  N = keep data (run uninstall again later to remove it)"
  local ans=""
  if [[ -t 0 ]]; then
    read -r -p "Remove data? [y/N] " ans || true
  else
    echo "(non-interactive: keeping data)"
    ans="n"
  fi
  case "${ans,,}" in
    y|yes) return 0 ;;
    *) return 1 ;;
  esac
}
